import assert from 'node:assert/strict';

export async function checkInformation(page,request,evidence) {
  const initial=await request('/information/settings');
  assert(initial.enabled&&initial.location,'Configure a city and enable lookups before this real integration check');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  const panel=page.locator('.location-settings');
  await panel.getByText(initial.location.name+', '+initial.location.country,{exact:true}).waitFor();
  const zone=panel.getByLabel('Default timezone',{exact:true});
  await zone.fill('UTC');
  await panel.getByRole('button',{name:'Save timezone',exact:true}).click();
  await panel.getByText('Defaults saved on this computer.',{exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('.clock')?.textContent.includes('UTC'));
  await page.reload();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await zone.waitFor();
  assert.equal(await zone.inputValue(),'UTC');
  evidence.timezoneSurvivesRefresh=true;
  await zone.fill(initial.timezone);
  await panel.getByRole('button',{name:'Save timezone',exact:true}).click();
  await panel.getByText('Defaults saved on this computer.',{exact:true}).waitFor();
  await page.waitForFunction(zone=>document.querySelector('.clock')?.textContent.includes(zone),initial.timezone,{timeout:10000});
  await panel.getByLabel('Find city or town',{exact:true}).fill(initial.location.name);
  await panel.getByRole('button',{name:'Search cities',exact:true}).click();
  await panel.getByRole('button',{name:'Use this city',exact:true}).first().waitFor({timeout:15000});
  evidence.realCitySearch=true;
  const checkbox=panel.getByLabel('Enable internet information lookups',{exact:true});
  await checkbox.uncheck();
  await panel.getByText('Defaults saved on this computer.',{exact:true}).waitFor();
  await page.waitForFunction(async()=>!(await(await fetch('/api/information/settings')).json()).enabled);
  const blocked=await page.evaluate(async()=>{
    const {csrf}=await(await fetch('/api/auth/session')).json();
    return (await fetch('/api/information/lookup',{method:'POST',headers:{'Content-Type':'application/json','X-CSRF-Token':csrf},body:JSON.stringify({kind:'weather'})})).status;
  });
  assert.equal(blocked,400);
  evidence.disabledLookupRefused=true;
  await checkbox.check();
  await page.waitForFunction(async()=>(await(await fetch('/api/information/settings')).json()).enabled);
  const weather=await request('/information/lookup',{kind:'weather'});
  assert.equal(weather.location.name,initial.location.name);
  assert.equal(weather.timezone,initial.timezone);
  evidence.weatherSource=weather.provider;
  await page.setViewportSize({width:412,height:915});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.screenshot({path:'/tmp/jarvis-location-settings-mobile.png'});
  await page.setViewportSize({width:1512,height:982});
  await page.getByRole('button',{name:'Command center',exact:true}).click();
  const prompt="What's the current USD/PHP exchange rate?";
  await page.getByRole('textbox',{name:'Your instruction',exact:true}).fill(prompt);
  await page.getByRole('button',{name:'Send instruction',exact:true}).click();
  await page.getByRole('button',{name:'Cancel generation',exact:true}).waitFor();
  await page.getByRole('button',{name:'Send instruction',exact:true}).waitFor({timeout:120000});
  assert.equal(await page.getByRole('alert').count(),0);
  const answer=await page.locator('.message.assistant').last().innerText();
  assert.match(answer,/Frankfurter daily reference rate dated/);
  const source=page.locator('.message.assistant').last().getByRole('link',{name:'Frankfurter',exact:true});
  assert.equal(await source.getAttribute('href'),'https://frankfurter.dev/');
  await page.reload();
  await page.locator('.message.assistant').last().waitFor();
  assert.match(await page.locator('.message.assistant').last().innerText(),/Frankfurter daily reference rate dated/);
  evidence.realHermesFxReply=true;
  evidence.sourceLinksAndHistory=true;
}
